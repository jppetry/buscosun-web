/**
 * gen-country-borders.mjs — writes `src/pointForecast/countryBorders.ts` from `public/countries/{DE,AT,CH}.geojson`
 * (V-FR-9, `audit/fusion-release.md` §8.12): the borders `pickCountry` tests in the zone where the country boxes overlap.
 * Each ring is clipped (Sutherland–Hodgman) to the rectangle where that country's box overlaps another box — the only
 * place `pickCountry` tests a border; for a point inside that rectangle the even–odd test is unchanged. Douglas–Peucker
 * with TOL_DEG, coordinates quantised to 1e-4° (≈ 10 m); a ring that would fall below 4 points stays unsimplified
 * (enclaves: Büsingen, Jungholz, Campione). Rings are flat [lng, lat, …] × 1e4 integers.
 *
 *   node --experimental-strip-types --import ./scripts/lib/register-ts.mjs scripts/gen-country-borders.mjs [--tol=0.002]
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { COUNTRY_PROFILES } from '../src/countryProfiles.ts';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const TOL_DEG = Number(process.argv.find((a) => a.startsWith('--tol='))?.slice(6) ?? 0.002);
const Q = 1e4;

function dp(pts, tol) {
  if (pts.length < 3) return pts;
  const keep = new Uint8Array(pts.length);
  keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    const [x1, y1] = pts[a], [x2, y2] = pts[b];
    const dx = x2 - x1, dy = y2 - y1, len = Math.hypot(dx, dy) || 1e-12;
    let best = -1, bestD = tol;
    for (let i = a + 1; i < b; i++) {
      const d = Math.abs(dy * (pts[i][0] - x1) - dx * (pts[i][1] - y1)) / len;
      if (d > bestD) { bestD = d; best = i; }
    }
    if (best >= 0) { keep[best] = 1; stack.push([a, best], [best, b]); }
  }
  return pts.filter((_, i) => keep[i]);
}

const CC = ['DE', 'AT', 'CH'];
/** Rectangle per country: bbox of its box's overlaps with the other boxes, padded 0.01°. */
const clipRect = (c) => {
  const a = COUNTRY_PROFILES[c].bounds;
  let r = null;
  for (const o of CC) {
    if (o === c) continue;
    const b = COUNTRY_PROFILES[o].bounds;
    const x0 = Math.max(a.lngMin, b.lngMin), x1 = Math.min(a.lngMax, b.lngMax), y0 = Math.max(a.latMin, b.latMin), y1 = Math.min(a.latMax, b.latMax);
    if (x0 >= x1 || y0 >= y1) continue;
    r = r ? [Math.min(r[0], x0), Math.min(r[1], y0), Math.max(r[2], x1), Math.max(r[3], y1)] : [x0, y0, x1, y1];
  }
  return r && [r[0] - 0.01, r[1] - 0.01, r[2] + 0.01, r[3] + 0.01];
};
/** Sutherland–Hodgman against an axis-aligned rectangle (open ring in, open ring out). */
function clip(ring, [x0, y0, x1, y1]) {
  const edges = [[(p) => p[0] >= x0, (a, b) => [x0, a[1] + ((b[1] - a[1]) * (x0 - a[0])) / (b[0] - a[0])]],
    [(p) => p[0] <= x1, (a, b) => [x1, a[1] + ((b[1] - a[1]) * (x1 - a[0])) / (b[0] - a[0])]],
    [(p) => p[1] >= y0, (a, b) => [a[0] + ((b[0] - a[0]) * (y0 - a[1])) / (b[1] - a[1]), y0]],
    [(p) => p[1] <= y1, (a, b) => [a[0] + ((b[0] - a[0]) * (y1 - a[1])) / (b[1] - a[1]), y1]]];
  let out = ring;
  for (const [inside, cut] of edges) {
    const inp = out; out = [];
    for (let i = 0; i < inp.length; i++) {
      const cur = inp[i], prev = inp[(i + inp.length - 1) % inp.length];
      if (inside(cur)) { if (!inside(prev)) out.push(cut(prev, cur)); out.push(cur); }
      else if (inside(prev)) out.push(cut(prev, cur));
    }
    if (!out.length) break;
  }
  return out;
}
const out = {};
const stats = [];
for (const c of CC) {
  const rect = clipRect(c);
  const f = JSON.parse(readFileSync(join(ROOT, 'public', 'countries', `${c}.geojson`), 'utf8'));
  const polys = f.geometry.type === 'MultiPolygon' ? f.geometry.coordinates : [f.geometry.coordinates];
  const rings = [];
  let before = 0, after = 0;
  for (const poly of polys) for (const ring of poly) {
    before += ring.length;
    // Clip to the overlap rectangle, then split the ring at its farthest point so DP keeps both halves.
    const open = clip(ring.slice(0, -1), rect);
    if (open.length < 3) continue;
    let far = 1, fd = -1;
    for (let i = 1; i < open.length; i++) { const d = Math.hypot(open[i][0] - open[0][0], open[i][1] - open[0][1]); if (d > fd) { fd = d; far = i; } }
    let s = [...dp(open.slice(0, far + 1), TOL_DEG).slice(0, -1), ...dp([...open.slice(far), open[0]], TOL_DEG).slice(0, -1)];
    if (s.length < 4) s = open;
    const flat = s.flatMap(([x, y]) => [Math.round(x * Q), Math.round(y * Q)]);
    after += s.length;
    rings.push(flat);
  }
  out[c] = rings;
  stats.push(`${c} ${before} → ${after} Punkte, ${rings.length} Ringe, Rechteck ${rect.map((v) => v.toFixed(2)).join('/')}`);
}

const body = Object.entries(out).map(([c, rings]) => `  ${c}: [\n${rings.map((r) => `    [${r.join(',')}],`).join('\n')}\n  ],`).join('\n');
const ts = `/**
 * GENERATED by scripts/gen-country-borders.mjs from public/countries/{DE,AT,CH}.geojson — do not edit by hand.
 * Douglas–Peucker ${TOL_DEG}° (≈ ${Math.round(TOL_DEG * 75000)}–${Math.round(TOL_DEG * 111000)} m), quantised 1e-4°. ${stats.join(' · ')}.
 * Rings: flat [lng, lat, …] × 1e4; all rings of a country together under the even–odd rule (holes = enclaves).
 * Clipped to the overlap rectangles (COUNTRY_BORDER_CLIP) — valid only inside them; \`pickCountry\` tests a border only
 * where the country boxes overlap (V-FR-9, audit/fusion-release.md §8.12).
 */
import type { Country } from '../types';

export const COUNTRY_BORDER_TOL_DEG = ${TOL_DEG};
/** The rectangle each country's rings are clipped to: [lngMin, latMin, lngMax, latMax]. Valid only inside it. */
export const COUNTRY_BORDER_CLIP: Readonly<Record<Country, readonly number[]>> = ${JSON.stringify(Object.fromEntries(CC.map((c) => [c, clipRect(c).map((v) => +v.toFixed(4))])))};
export const COUNTRY_BORDERS: Readonly<Record<Country, readonly (readonly number[])[]>> = {
${body}
};
`;
writeFileSync(join(ROOT, 'src', 'pointForecast', 'countryBorders.ts'), ts);
console.log(stats.join('\n'), `\n${(ts.length / 1024).toFixed(1)} KB`);
